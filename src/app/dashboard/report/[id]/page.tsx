import { redirect, notFound } from 'next/navigation'
import Link from 'next/link'
import { createClient } from '@/lib/supabase/server'
import { Button } from '@/components/ui/button'
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card'
import type { AIReportContent } from '@/types'

export default async function ReportPage({ params }: { params: { id: string } }) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()

  if (!user) redirect('/login')

  const { data: report } = await supabase
    .from('reports')
    .select('*')
    .eq('id', params.id)
    .eq('user_id', user.id)
    .single()

  if (!report) notFound()

  if (report.status === 'generating') {
    return <GeneratingState reportId={params.id} />
  }

  if (report.status === 'failed') {
    return <FailedState />
  }

  const content = report.ai_report_content as AIReportContent

  return (
    <div className="min-h-screen bg-slate-50">
      <header className="bg-white border-b border-slate-200">
        <div className="max-w-6xl mx-auto px-4 sm:px-6 h-16 flex items-center justify-between">
          <div className="flex items-center gap-4">
            <Link href="/dashboard">
              <Button variant="ghost" size="sm">← Dashboard</Button>
            </Link>
            <div className="flex items-center gap-2">
              <div className="w-8 h-8 bg-indigo-600 rounded-lg flex items-center justify-center">
                <span className="text-white font-bold text-sm">A</span>
              </div>
              <span className="font-semibold text-slate-900">AuditReady</span>
            </div>
          </div>
          <div className="flex items-center gap-2">
            <Button variant="outline" size="sm" onClick={undefined}>
              Download PDF
            </Button>
          </div>
        </div>
      </header>

      <main className="max-w-4xl mx-auto px-4 sm:px-6 py-8">
        <div className="mb-8">
          <div className="flex items-center gap-2 mb-2">
            <span className="text-xs bg-green-50 text-green-700 px-2 py-1 rounded-full">Complete</span>
          </div>
          <h1 className="text-3xl font-bold text-slate-900">Financial Health Report</h1>
          <p className="text-slate-500 mt-1">{report.period_month}</p>
          <p className="text-xs text-slate-400 mt-1">
            Generated {new Date(report.generated_at).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', hour: '2-digit', minute: '2-digit' })}
          </p>
        </div>

        <div className="space-y-6">
          <ReportSection letter="A" title="Business Snapshot" color="indigo">
            <p className="text-slate-700 leading-relaxed">{content.business_snapshot}</p>
          </ReportSection>

          <ReportSection letter="B" title="Revenue Story" color="blue">
            <p className="text-slate-700 leading-relaxed">{content.revenue_story}</p>
          </ReportSection>

          <ReportSection letter="C" title="Where Your Money Went" color="purple">
            <p className="text-slate-700 leading-relaxed">{content.where_money_went}</p>
          </ReportSection>

          <ReportSection letter="D" title="Cash Position" color="teal">
            <p className="text-slate-700 leading-relaxed">{content.cash_position}</p>
          </ReportSection>

          <ReportSection letter="E" title="Watch Out For" color="amber">
            <ul className="space-y-3">
              {content.watch_out_for?.map((item, i) => (
                <li key={i} className="flex items-start gap-3">
                  <span className="w-5 h-5 bg-amber-100 text-amber-700 rounded-full flex items-center justify-center text-xs font-bold flex-shrink-0 mt-0.5">!</span>
                  <p className="text-slate-700 text-sm leading-relaxed">{item}</p>
                </li>
              ))}
            </ul>
          </ReportSection>

          <ReportSection letter="F" title="Your Action List" color="green">
            <ol className="space-y-3">
              {content.action_list?.map((item, i) => (
                <li key={i} className="flex items-start gap-3">
                  <span className="w-6 h-6 bg-green-100 text-green-700 rounded-full flex items-center justify-center text-xs font-bold flex-shrink-0 mt-0.5">{i + 1}</span>
                  <p className="text-slate-700 text-sm leading-relaxed">{item}</p>
                </li>
              ))}
            </ol>
          </ReportSection>
        </div>

        <div className="mt-8 pt-8 border-t border-slate-200 text-center">
          <p className="text-xs text-slate-400">
            This report was generated by AuditReady using your Xero data. It is for informational purposes only and does not constitute financial advice.
          </p>
        </div>
      </main>
    </div>
  )
}

function ReportSection({
  letter,
  title,
  color,
  children,
}: {
  letter: string
  title: string
  color: string
  children: React.ReactNode
}) {
  const colorMap: Record<string, string> = {
    indigo: 'bg-indigo-600',
    blue: 'bg-blue-600',
    purple: 'bg-purple-600',
    teal: 'bg-teal-600',
    amber: 'bg-amber-500',
    green: 'bg-green-600',
  }

  return (
    <Card className="border-slate-200 shadow-sm">
      <CardHeader className="pb-3">
        <div className="flex items-center gap-3">
          <div className={`w-8 h-8 ${colorMap[color] || 'bg-indigo-600'} rounded-lg flex items-center justify-center`}>
            <span className="text-white font-bold text-sm">{letter}</span>
          </div>
          <CardTitle className="text-lg font-semibold text-slate-900">{title}</CardTitle>
        </div>
      </CardHeader>
      <CardContent>{children}</CardContent>
    </Card>
  )
}

function GeneratingState({ reportId }: { reportId: string }) {
  return (
    <div className="min-h-screen bg-slate-50 flex items-center justify-center">
      <div className="text-center">
        <div className="w-12 h-12 border-4 border-indigo-600 border-t-transparent rounded-full animate-spin mx-auto mb-4"></div>
        <h2 className="text-xl font-semibold text-slate-900 mb-2">Generating your report...</h2>
        <p className="text-slate-500 mb-6">This takes about 30-60 seconds</p>
        <p className="text-xs text-slate-400">Report ID: {reportId}</p>
      </div>
    </div>
  )
}

function FailedState() {
  return (
    <div className="min-h-screen bg-slate-50 flex items-center justify-center">
      <div className="text-center max-w-md">
        <div className="w-12 h-12 bg-red-100 rounded-full flex items-center justify-center mx-auto mb-4">
          <svg className="w-6 h-6 text-red-600" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
          </svg>
        </div>
        <h2 className="text-xl font-semibold text-slate-900 mb-2">Report generation failed</h2>
        <p className="text-slate-500 mb-6">Something went wrong while generating this report.</p>
        <Link href="/dashboard/generate">
          <Button>Try again</Button>
        </Link>
      </div>
    </div>
  )
}
